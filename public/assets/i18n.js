const get = (k, d) => { try { return localStorage.getItem(k) || d; } catch { return d; } };
let lang = get('kl-lang', 'bi');
function t(key, vars) {
  const e = T[key];
  let s = e ? (e[lang] ?? e.en) : key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, v) => (v === 's' ? (vars.n === 1 ? '' : 's') : vars[v] ?? ''));
  return s;
}
function setLang(l, justThisPage) { lang = l; if (!justThisPage) { try { localStorage.setItem('kl-lang', l); } catch {} } document.documentElement.lang = l === 'bi' ? 'bi' : 'en'; }
// Fill in static page text marked with data-t="key" (and data-t-ph for placeholders).
function applyStatic(root = document) {
  root.querySelectorAll('[data-t]').forEach(el => { el.innerHTML = t(el.dataset.t, el.dataset.tv ? JSON.parse(el.dataset.tv) : undefined); });
  root.querySelectorAll('[data-t-ph]').forEach(el => { el.placeholder = t(el.dataset.tPh); el.setAttribute('aria-label', t(el.dataset.tPh)); });
}
// A header button that switches language and redraws the page.
function langButton(onChange) {
  const b = document.getElementById('langBtn'); if (!b) return;
  const paint = () => { b.textContent = t('langSwitch'); };
  paint();
  b.onclick = () => { setLang(lang === 'bi' ? 'en' : 'bi'); paint(); applyStatic(); onChange && onChange(); };
}
setLang(lang);
